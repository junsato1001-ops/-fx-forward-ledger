"""D10: the generated CODE_MANIFEST_V1 must list exactly the repository's m1macro_*.yml workflows (plus the required
files), checked by an independent path (manifest_gate does not reuse manifest.py's file selection)."""
import hashlib
import tempfile
from pathlib import Path

from m1macro import manifest, manifest_gate as G

REQ = ("m1macro/manifest.py", "m1macro/manifest_gate.py", ".github/workflows/m1macro_forward.yml",
       ".github/workflows/m1macro_snapshot_acquire.yml", ".github/workflows/m1macro_gates.yml")


def _mk(root, rels):
    for r in rels:
        p = Path(root, r); p.parent.mkdir(parents=True, exist_ok=True); p.write_bytes(r.encode() + b"\n")


def _man(root, rels):
    ents = sorted((r, hashlib.sha256(Path(root, r).read_bytes()).hexdigest()) for r in rels)
    return ("CODE_MANIFEST_V1\n" + "".join(f"{p},{h}\n" for p, h in ents)).encode()


def run():
    # the real candidate: manifest generated by manifest.py, checked by the gate
    real = G.check(manifest.manifest_bytes(), str(manifest.ROOT))
    assert real["pass"], real["violations"]
    assert set(REQ) <= {p for p, _ in G.parse(manifest.manifest_bytes())}
    # a generator bug (workflow pattern dropped) is caught: the gate does not share the generator's file selection
    old = list(manifest.PATTERNS)
    try:
        manifest.PATTERNS[:] = [p for p in old if "workflows" not in p]
        bad = G.check(manifest.manifest_bytes(), str(manifest.ROOT))
        assert not bad["pass"] and any(v.startswith("WORKFLOW_NOT_IN_MANIFEST:") for v in bad["violations"])
    finally:
        manifest.PATTERNS[:] = old
    with tempfile.TemporaryDirectory() as td:
        base = list(REQ) + [".github/workflows/m1macro_dev.yml", ".github/workflows/forward.yml", "m1macro/x.py"]
        _mk(td, base)
        listed = [r for r in base if r != ".github/workflows/forward.yml"]                 # non-m1macro workflow: out of scope
        assert G.check(_man(td, listed), td)["pass"]
        # a workflow added to the repository but not to the manifest
        _mk(td, [".github/workflows/m1macro_new.yml"])
        r = G.check(_man(td, listed), td)
        assert r["violations"] == ["WORKFLOW_NOT_IN_MANIFEST:.github/workflows/m1macro_new.yml"]
        assert G.check(_man(td, listed + [".github/workflows/m1macro_new.yml"]), td)["pass"]
        Path(td, ".github/workflows/m1macro_new.yml").unlink()
        # a manifest entry for a workflow that is not in the repository
        _mk(td, [".github/workflows/m1macro_gone.yml"]); m = _man(td, listed + [".github/workflows/m1macro_gone.yml"])
        Path(td, ".github/workflows/m1macro_gone.yml").unlink()
        r = G.check(m, td)
        assert "MANIFEST_WORKFLOW_NOT_IN_REPOSITORY:.github/workflows/m1macro_gone.yml" in r["violations"]
        # each required file, if absent from the manifest, fails
        for q in REQ:
            r = G.check(_man(td, [x for x in listed if x != q]), td)
            assert "REQUIRED_MISSING:" + q in r["violations"], q
        # a stale hash, and malformed manifests
        m = _man(td, listed); Path(td, "m1macro/x.py").write_bytes(b"changed\n")
        assert G.check(m, td)["violations"] == ["ENTRY_SHA_MISMATCH:m1macro/x.py"]
        for mal in (b"", b"CODE_MANIFEST_V1", b"X\n", b"CODE_MANIFEST_V1\nb,\n", m.replace(b"\n", b"\r\n")):
            assert not G.check(mal, td)["pass"]
        lines = m.split(b"\n")
        assert not G.check(b"\n".join([lines[0], lines[2], lines[1]] + lines[3:]), td)["pass"]  # unsorted
    return {"ok": True, "n_entries": real["n_entries"], "workflows": real["workflows_manifest"]}


if __name__ == "__main__":
    print(run())
